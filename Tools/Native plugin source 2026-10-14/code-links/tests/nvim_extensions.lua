vim.opt.rtp:prepend('/Users/gradyclopton/Projects/code-links/nvim')
local m=require('code_links')
local root='/Users/gradyclopton/ObsidianVaults/code_links_lab'
local raw='!{{demo/fragments.py#L1-L2,L7-L8}}'
m.open(root,raw)
assert(vim.wait(5000,function()return vim.b.code_links_excerpt~=nil end,20))
assert(vim.b.code_links_excerpt.line_numbers[4]==7)
vim.api.nvim_win_set_cursor(0,{4,0});m.open_source()
assert(vim.wait(5000,function()return vim.b.code_links_excerpt==nil end,20))
assert(vim.api.nvim_win_get_cursor(0)[1]==7)
assert(vim.bo.modifiable)
local n=#vim.api.nvim_list_wins()
m.open(root,raw,2,'split','source')
assert(vim.wait(5000,function()return #vim.api.nvim_list_wins()==n+1 end,20))
assert(vim.api.nvim_win_get_cursor(0)[1]==2)
m.open(root,raw,nil,'tab','folder')
assert(vim.wait(5000,function()return vim.api.nvim_buf_get_name(0)==root..'/demo' end,20))
print('PASS: disjoint excerpt original line, editable source, split and folder')
vim.cmd('qa!')
