import {build} from 'esbuild';
import {strict as assert} from 'node:assert';
const bundle = await build({entryPoints:['link-syntax.ts'],bundle:true,write:false,format:'esm',platform:'node'});
const {codeLinkRegex,reservedTarget} = await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const matches = s => [...s.matchAll(codeLinkRegex())].map(m=>m[0]);
assert.deepEqual(matches('A {{blank:a}} and {{blank:b-2}}.'), []);
assert.deepEqual(matches('!{{blank:a}} {{ blank:a}} {{BLANK:a}}'), []);
assert.deepEqual(matches('A {{blank:a}}, {{scripts/a.py|Code}}, {{blank:b}}, !{{bdm:run/OUTCAR#L10-L20|Results}}{height=10}'), ['{{scripts/a.py|Code}}','!{{bdm:run/OUTCAR#L10-L20|Results}}{height=10}']);
assert.deepEqual(matches('{{blank.py}} {{bdm:blank.py}}'), ['{{blank.py}}','{{bdm:blank.py}}']);
assert.equal(reservedTarget('blank:a'),true);
assert.equal(reservedTarget('blank:'),true);
assert.equal(reservedTarget('bdm:run'),false);
console.log('Code Links / Study Studio marker isolation regression passed');
const {linkTokens,groupItems}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const group='{{links:Evidence|{{demo.py#L2-L4|Code}}; [[Theory|Model]]; [Paper](https://example.com/paper)}}';
assert.deepEqual(linkTokens('Before '+group+' after').map(x=>x.raw),[group]);
assert.deepEqual(groupItems(group).items,['{{demo.py#L2-L4|Code}}','[[Theory|Model]]','[Paper](https://example.com/paper)']);
assert.equal(linkTokens('``dir:demo:src|Source``')[0].raw,'``dir:demo:src|Source``');
assert.equal(linkTokens('``ordinary code``').length,0);
assert.throws(()=>groupItems('{{links:Evidence|random prose}}'));
assert.equal(linkTokens('{{blank:a}} '+group).length,1);
console.log('PASS directory opt-in and mixed reference group parser');
